import { CoreGraphOutput, RankingResult } from '../types.js';
import { ExporterOptions } from './types.js';
import { BlastRadiusCalculator } from './blast_radius.js';

export class AgentsSkillsExporter {
  public static export(
    graph: CoreGraphOutput,
    ranking: RankingResult,
    options: ExporterOptions
  ): string {
    const topModules = ranking.rankedFiles
      .filter((f) => !f.isBoilerplate)
      .slice(0, 6);

    const blastMap = BlastRadiusCalculator.calculate(topModules, graph.edges);

    return `---
name: ${options.repoName.replace('/', '-')}-architecture
description: Architecture graph, core gravity wells, and blast radius rules for ${options.repoName}.
version: 1.0.0
---

# Architecture Skill: ${options.repoName}

## Overview
Automated architectural context generated by GitXray. Use this skill when modifying, refactoring, or generating features for ${options.repoName}.

## Core Modules & Impact Table
${topModules
  .map((m) => {
    const blast = blastMap.get(m.id);
    return `- **\`${m.id}\`** (Stage ${m.stage ?? 0}, Centrality ${(m.score * 100).toFixed(1)}%): Affects ${blast?.transitiveDownstreamCount ?? 0} downstream files.`;
  })
  .join('\n')}

## Working Invariants
1. Consult \`${topModules[0]?.id || 'core module'}\` before proposing cross-cutting changes.
2. Maintain strict DAG ordering across topological stages.
3. Review downstream blast radius when altering public function signatures.
`;
  }
}
