import { CoreGraphOutput, RankingResult, CoreGraphEdge } from '../types.js';
import { ExporterOptions } from './types.js';
import { BlastRadiusCalculator } from './blast_radius.js';

export class ClaudeMdExporter {
  public static export(
    graph: CoreGraphOutput,
    ranking: RankingResult,
    options: ExporterOptions
  ): string {
    const limit = options.maxTopModules ?? 10;
    const topModules = ranking.rankedFiles
      .filter((f) => !f.isBoilerplate)
      .slice(0, limit);

    const blastMap = BlastRadiusCalculator.calculate(topModules, graph.edges);

    // Identify entrypoints: files with in-degree = 0 in import graph (nothing imports them)
    // In our edge model: (A imports B) -> edge source A, target B.
    // Files that are sources of imports but never imported by anything are entrypoints / CLI / routes.
    const targets = new Set(graph.edges.map((e: CoreGraphEdge) => e.target));
    const entrypoints = ranking.rankedFiles
      .filter((f) => !targets.has(f.id) && !f.isBoilerplate)
      .slice(0, 5)
      .map((f) => f.id);

    const stagesCount = ranking.stages.length;

    let doc = `# CLAUDE.md — Architecture & Agent Context for ${options.repoName}
*Generated by GitXray (https://gitxray.dev)*

## 1. Architectural Summary
- **Total Analyzed Files**: ${graph.nodes.length}
- **Internal Dependency Edges**: ${graph.edges.length}
- **Topological Stages**: ${stagesCount}
- **Primary Core Gravity Well**: \`${topModules[0]?.id || 'N/A'}\`

## 2. Core Gravity Wells & High-Centrality Modules
These modules carry the highest PageRank and betweenness centrality. Focus comprehension and modifications here:

| Module | Score | Stage | Dependents | Transitive Blast Radius |
|---|---|---|---|---|
`;

    for (const mod of topModules) {
      const blast = blastMap.get(mod.id);
      const dependentsCount = blast?.directDependents.length ?? 0;
      const transitiveCount = blast?.transitiveDownstreamCount ?? 0;
      doc += `| \`${mod.id}\` | ${(mod.score * 100).toFixed(1)}% | S${mod.stage ?? 0} | ${dependentsCount} direct | ${transitiveCount} downstream |\n`;
    }

    doc += `\n## 3. Entry Points & High-Level Interfaces\n`;
    if (entrypoints.length > 0) {
      for (const ep of entrypoints) {
        doc += `- \`${ep}\`\n`;
      }
    } else {
      doc += `- Root package entrypoints or CLI commands.\n`;
    }

    doc += `\n## 4. Topological Stage Ordering (Dependency Flow DAG)
Changes propagate downstream from earlier stages to later stages:
`;

    ranking.stages.slice(0, 8).forEach((stageFiles, stageIdx) => {
      const formattedFiles = stageFiles.slice(0, 4).map((f) => `\`${f}\``).join(', ');
      const extra = stageFiles.length > 4 ? ` + ${stageFiles.length - 4} more` : '';
      doc += `- **Stage ${stageIdx}**: ${formattedFiles}${extra}\n`;
    });

    if (options.includeBlastRadius !== false) {
      doc += `\n## 5. Blast Radius Invariants\n`;
      for (const mod of topModules.slice(0, 5)) {
        const blast = blastMap.get(mod.id);
        const directList = (blast?.directDependents || []).slice(0, 3).map((f) => `\`${f}\``).join(', ');
        doc += `- **Modifying \`${mod.id}\`**: Affects ${blast?.transitiveDownstreamCount || 0} downstream files${directList ? ` (including ${directList})` : ''}.\n`;
      }
    }

    if (options.includeInvariants !== false) {
      doc += `\n## 6. Architectural Invariants for AI Agents
1. **Dependency Direction**: Strictly import from lower stages to higher stages. Never introduce circular dependencies across stages.
2. **Kernel Cohesion**: Modifications to core gravity wells must maintain backward-compatible exported signatures.
3. **Deterministic Separation**: Keep pure domain algorithms isolated from I/O and rendering layers.
`;
    }

    return doc;
  }
}
